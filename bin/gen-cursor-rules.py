#!/usr/bin/env python3
"""Generate .cursor/rules/*.mdc from the Claude rules and agents.

The Claude files are the only source. Each .mdc is a short pointer that pulls in
its source file, so the Cursor and Claude copies can never drift apart.

    python3 bin/gen-cursor-rules.py          # rewrite .cursor/rules/
    python3 bin/gen-cursor-rules.py --check  # exit 1 if any .mdc is out of date

After adding a rule or agent, add one line to RULES or AGENTS below and re-run.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, ".cursor", "rules")

# name -> (description, alwaysApply). Always-on rules cost context in every chat,
# so only the rules that apply to every action are always on.
RULES = {
    "kanban-workflow": ("Kanban workflow: the 12 columns, who may move a ticket where, required documents per move", True),
    "solo-vs-team-mode": ("Operating mode (solo vs team) and the autonomy each mode gives the AI", True),
    "source-control": ("Branches, PRs, commits, protected branches and commit attribution", True),
    "secrets-management": ("Secrets and .env handling: never commit .env files or keys; pre-work secrets audit", True),
    "ticket-discipline": ("Board-first work, blocker labels, dual-channel status, chat-to-ticket intake", True),
    "agent-communication": ("How agents hand off work and talk on tickets (parent and sub-issues)", False),
    "client-facing-boundary": ("What may appear in client-visible commits, PRs, release notes and docs", False),
    "contract-driven-flow": ("Features touching backend and frontend: contract sub-issue, validation gate, tests first", False),
    "erp-guardrails": ("Hard rules for ERP work in erp-core and erp-fe: Flyway register, worktrees, machine limits, demo DB", False),
    "framework-observation": ("Filing a framework-gap ticket on the AISDLC board with bin/aisdlc-observe.sh", False),
    "gh-recipes": ("gh CLI and GraphQL recipes: board items, Status/Priority fields, sub-issues", False),
    "size-audit": ("Size audit before planning or building; red thresholds and tech-debt tickets", False),
}
AGENTS = {
    "planner": "Act as @planner: FRD help, execution plans, API contracts, decision logs",
    "tester": "Act as @tester: write failing tests from the contract before any code",
    "builder": "Act as @builder: build the erp-core backend (Spring Boot) to make the tests pass",
    "fe-builder": "Act as @fe-builder: build erp-fe screens (Next.js) from the contract and design boards",
    "shipper": "Act as @shipper: staging deploy, rework, hotfix lane, release notes, production checklist",
    "ticket-manager": "Act as @ticket-manager: enforce kanban rules and move tickets on the board",
    "project-wiki": "Act as @project-wiki: keep the product wiki in step with what is built",
}

HEADER = "<!-- Generated by bin/gen-cursor-rules.py from {src}. Edit the source, then re-run. -->\n"


def render(description, always, src, title, body):
    return (
        "---\n"
        f"description: {description}\n"
        f"alwaysApply: {'true' if always else 'false'}\n"
        "---\n"
        + HEADER.format(src=src)
        + f"\n# {title}\n\n{body}\n\n@../../{src}\n"
    )


def expected():
    files = {}
    for name, (desc, always) in RULES.items():
        src = f".claude/rules/{name}.md"
        files[f"{name}.mdc"] = render(
            desc, always, src, title_of(src),
            f"This rule lives in `{src}`, included below. Read it in full and follow it exactly. "
            "If anything here seems to differ from that file, the file wins.")
    rows = []
    for name, desc in AGENTS.items():
        src = f".claude/agents/{name}.md"
        files[f"persona-{name}.mdc"] = render(
            desc, False, src, f"Persona: @{name}",
            f"When asked to act as @{name}, take on the role defined in `{src}`, included below. "
            "Follow it exactly, including its hand-off rules and the rules it links to.")
        rows.append(f"| @{name} | `{src}` | `persona-{name}.mdc` |")
    files["framework-agents.mdc"] = render(
        "Index of the AISDLC agents (personas) and where each is defined", False,
        "CLAUDE.md", "Framework Agents",
        "Pick the persona for the current column, then open its source file.\n\n"
        "| Agent | Source | Cursor rule |\n|---|---|---|\n" + "\n".join(rows))
    return files


def title_of(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("# "):
                return line[2:].strip()
    return os.path.basename(path)


def main():
    check = "--check" in sys.argv[1:]
    want = expected()
    missing_src = [n for n in list(RULES) if not os.path.isfile(os.path.join(ROOT, f".claude/rules/{n}.md"))]
    missing_src += [n for n in AGENTS if not os.path.isfile(os.path.join(ROOT, f".claude/agents/{n}.md"))]
    if missing_src:
        print("source files missing for: " + ", ".join(missing_src))
        return 1
    have = {f for f in os.listdir(OUT) if f.endswith(".mdc")} if os.path.isdir(OUT) else set()
    stale = sorted(f for f in want if not os.path.isfile(os.path.join(OUT, f))
                   or open(os.path.join(OUT, f), encoding="utf-8").read() != want[f])
    extra = sorted(have - set(want))
    if check:
        for f in stale:
            print(f"out of date: .cursor/rules/{f}")
        for f in extra:
            print(f"no source for: .cursor/rules/{f}")
        if stale or extra:
            print("run: python3 bin/gen-cursor-rules.py")
            return 1
        print("Cursor rules are up to date.")
        return 0
    os.makedirs(OUT, exist_ok=True)
    for f in extra:
        os.remove(os.path.join(OUT, f))
    for f, text in want.items():
        with open(os.path.join(OUT, f), "w", encoding="utf-8") as fh:
            fh.write(text)
    print(f"wrote {len(want)} files, removed {len(extra)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
